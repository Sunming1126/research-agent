def audit_gaps(audit, markdown):
    """审查未覆盖或证据无法定位时留下诊断，不改写模型正文。"""
    rows = audit.get('coverage')
    if not isinstance(rows, list) or len(rows) != len(REQUIREMENTS):
        return ['E逐项审查不完整：需要八项正文覆盖证据，不能仅声明ok。']
    keys = [r.get('key') for r in rows if isinstance(r, dict)]
    if len(keys) != len(rows) or not all(isinstance(key, str) for key in keys) or set(keys) != set(REQUIREMENTS):
        return ['E逐项审查缺项或重复。']
    paragraphs = {f'p{i+1}': text for i, text in enumerate(markdown.split('\n\n')) if text.strip()}
    normalized = re.sub(r'[\s*#`]', '', markdown)
    gaps = []
    for row in rows:
        key, status = row['key'], row.get('status')
        if not isinstance(status, str) or status not in {'supported', 'partial', 'missing'}:
            gaps.append('E审查条目结构错误：' + key)
        elif status != 'supported':
            gaps.append(f'E要点{key}仍不完整，需补足：{REQUIREMENTS[key]}')
        elif 'paragraph_ids' in row:
            ids = row['paragraph_ids']
            if not isinstance(ids, list) or not 1 <= len(ids) <= 2 or not all(isinstance(i, str) and i in paragraphs for i in ids):
                gaps.append('E审查证据段落编号无效：' + key)
        else:
            excerpt = row.get('excerpt')
            if not isinstance(excerpt, str) or not excerpt.strip() or re.sub(r'[\s*#`]', '', excerpt) not in normalized:
                gaps.append('E审查证据不是当前正文连续原句：' + key)
    return gaps


